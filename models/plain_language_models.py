"""
Data models for the Plain-Language Patient Guide.

The guide is generated by agents/plain_language_agent.py, reviewed and
approved by a coordinator, and only approved items are shown to patients.
"""

from typing import List, Literal, Optional

from pydantic import BaseModel, Field


SectionName = Literal[
    "inclusion_criteria",
    "exclusion_criteria",
    "visits",
    "procedures",
    "safety_information",
]


class GlossaryTerm(BaseModel):
    """A medical term found in the protocol and its plain-language meaning."""

    term: str
    explanation: str


class PlainLanguageRewrite(BaseModel):
    """Schema the language model must return for a single statement."""

    plain_text: str


class GuideItem(BaseModel):
    """One protocol statement rewritten for patients."""

    section: SectionName
    original_text: str
    plain_text: str
    source_page: Optional[int] = None
    terms_explained: List[GlossaryTerm] = Field(default_factory=list)

    # How the plain text was produced:
    # "llm"         -> rewritten by the model and passed all safety checks
    # "fallback"    -> model output failed checks, original wording kept
    # "coordinator" -> edited by a human coordinator
    generated_by: Literal["llm", "fallback", "coordinator"] = "llm"
    needs_review: bool = False
    review_reasons: List[str] = Field(default_factory=list)

    # Human approval: patients only ever see approved items.
    approved: bool = False


class GuideSection(BaseModel):
    """A titled group of guide items."""

    title: str
    introduction: str
    items: List[GuideItem] = Field(default_factory=list)
    unavailable_message: Optional[str] = None


class PatientGuide(BaseModel):
    """Complete plain-language guide generated from a ProtocolAnalysis."""

    trial_title: Optional[str] = None
    protocol_id: Optional[str] = None

    who_can_join: GuideSection
    who_cannot_join: GuideSection
    visits: GuideSection
    procedures: GuideSection
    safety: GuideSection

    glossary: List[GlossaryTerm] = Field(default_factory=list)
    disclaimer: str

    def sections(self) -> List[GuideSection]:
        return [
            self.who_can_join,
            self.who_cannot_join,
            self.visits,
            self.procedures,
            self.safety,
        ]

    def all_items(self) -> List[GuideItem]:
        return [item for section in self.sections() for item in section.items]

    def flagged_items(self) -> List[GuideItem]:
        return [item for item in self.all_items() if item.needs_review]

    def approved_count(self) -> int:
        return sum(1 for item in self.all_items() if item.approved)

    def is_fully_approved(self) -> bool:
        items = self.all_items()
        return bool(items) and all(item.approved for item in items)
